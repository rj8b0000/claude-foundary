import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { buildManifest, loadManifestFile, sha256Hex } from "./manifest.js";

const RULES_FILE_PATH = ".claude-foundry/steering/rules.md";

async function fileExists(p) {
  try {
    await readFile(p);
    return true;
  } catch {
    return false;
  }
}

async function tryLoadManifest(projectRoot) {
  try {
    return await loadManifestFile(path.join(projectRoot, ".claude-foundry", "manifest.json"));
  } catch {
    return null;
  }
}

/** Render the resolved `rules` into one aggregate steering file, sorted for a stable diff. */
function renderRulesFile(rules) {
  if (!rules || rules.length === 0) return null;
  const sorted = [...rules].sort((a, b) => a.id.localeCompare(b.id));
  const lines = [
    "# Active coding rules",
    "",
    "Generated by ClaudeFoundry from the currently applied profiles. A rule listed",
    "as overridable in its profile can be edited here directly — ClaudeFoundry",
    "detects the edit and asks before ever replacing it again.",
    "",
    ...sorted.map((r) => `- **${r.id}** (from ${r.contributors.join(", ")}): ${r.text}`),
    "",
  ];
  return lines.join("\n");
}

/** Collect every named target (instructions, steeringDocs, and the synthesized rules file) that this composition would write. */
function collectTargets(resolvedConfig) {
  const targets = [...resolvedConfig.instructions, ...resolvedConfig.steeringDocs];
  const rulesContent = renderRulesFile(resolvedConfig.rules);
  if (rulesContent !== null) {
    targets.push({
      path: RULES_FILE_PATH,
      content: rulesContent,
      generatedBy: { profile: "<composed>", componentId: "rules" },
    });
  }
  return targets;
}

/**
 * Compute a safe write plan for a composition against a real project, without
 * touching the filesystem. Every entry is classified so a caller can preview
 * it and decide what to approve before anything is written.
 *
 * Statuses:
 *  - "create": new file, nothing in the way.
 *  - "update": a file ClaudeFoundry generated before, unedited since, whose
 *    content changed because a profile was updated. Safe to overwrite.
 *  - "unchanged": nothing to do.
 *  - "conflict-pre-existing-file": a file already exists at this path that
 *    ClaudeFoundry did not create. Never written without explicit force.
 *  - "user-edited": ClaudeFoundry created this file before, but its content
 *    no longer matches what was recorded — someone edited it by hand.
 *  - "previously-generated-now-missing": the manifest says ClaudeFoundry
 *    wrote this file, but it's gone from disk now.
 *  - "orphaned": a file the manifest tracks that no longer appears in the
 *    current composition (a profile was dropped or updated to exclude it).
 *    Never deleted automatically, regardless of force.
 *
 * @param {string} projectRoot
 * @param {{ ok: boolean, resolved: object, conflicts: object[] }} compositionResult
 */
export async function computePlan(projectRoot, compositionResult) {
  if (!compositionResult.ok) {
    throw new Error("cannot plan a composition that failed (conflictsWith) — resolve the selection first");
  }

  const manifest = await tryLoadManifest(projectRoot);
  const manifestByPath = new Map((manifest?.files ?? []).map((f) => [f.path, f]));
  const targets = collectTargets(compositionResult.resolved);
  const targetPaths = new Set(targets.map((t) => t.path));

  const writable = [];
  const blocked = [];

  for (const target of targets) {
    const absolutePath = path.join(projectRoot, target.path);
    const manifestEntry = manifestByPath.get(target.path);
    const existsOnDisk = await fileExists(absolutePath);
    const newHash = sha256Hex(target.content);

    if (!manifestEntry) {
      if (!existsOnDisk) {
        writable.push({ path: target.path, content: target.content, generatedBy: target.generatedBy, status: "create" });
      } else {
        blocked.push({ path: target.path, status: "conflict-pre-existing-file", content: target.content, generatedBy: target.generatedBy });
      }
      continue;
    }

    if (!existsOnDisk) {
      blocked.push({ path: target.path, status: "previously-generated-now-missing", content: target.content, generatedBy: target.generatedBy });
      continue;
    }

    const currentContent = await readFile(absolutePath, "utf8");
    const currentHash = sha256Hex(currentContent);

    if (currentHash !== manifestEntry.sha256) {
      blocked.push({ path: target.path, status: "user-edited", content: target.content, generatedBy: target.generatedBy });
      continue;
    }

    if (newHash === manifestEntry.sha256) {
      writable.push({ path: target.path, content: target.content, generatedBy: target.generatedBy, status: "unchanged" });
    } else {
      writable.push({ path: target.path, content: target.content, generatedBy: target.generatedBy, status: "update" });
    }
  }

  const orphaned = (manifest?.files ?? [])
    .filter((f) => !targetPaths.has(f.path))
    .map((f) => ({ path: f.path, status: "orphaned", generatedBy: f.generatedBy }));

  return {
    includedProfiles: compositionResult.includedProfiles,
    compositionConflicts: compositionResult.conflicts,
    writable,
    blocked,
    orphaned,
  };
}

/**
 * Apply a previously computed plan: writes every "create"/"update" entry,
 * leaves "unchanged" alone, and never touches anything in `blocked` or
 * `orphaned` unless its path is explicitly listed in `forcePaths` — and even
 * then, only for a blocked entry that carries `content` to (re)write.
 * Orphaned entries are never written to or deleted, regardless of force:
 * this engine does not implement deletion.
 *
 * @param {string} projectRoot
 * @param {ReturnType<typeof computePlan> extends Promise<infer T> ? T : never} plan
 * @param {string[]} [forcePaths]
 */
export async function applyPlan(projectRoot, plan, forcePaths = []) {
  const forceSet = new Set(forcePaths);
  const written = [];
  const skipped = [];

  for (const entry of plan.writable) {
    if (entry.status === "unchanged") continue;
    const absolutePath = path.join(projectRoot, entry.path);
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, entry.content, "utf8");
    written.push(entry);
  }

  for (const entry of plan.blocked) {
    if (forceSet.has(entry.path) && entry.content !== undefined) {
      const absolutePath = path.join(projectRoot, entry.path);
      await mkdir(path.dirname(absolutePath), { recursive: true });
      await writeFile(absolutePath, entry.content, "utf8");
      written.push({ ...entry, status: `forced-${entry.status}` });
    } else {
      skipped.push(entry);
    }
  }

  // Orphans are reported but never acted on — no force escape hatch for deletion.
  for (const entry of plan.orphaned) skipped.push(entry);

  // Build the new manifest from: everything just written, everything left
  // unchanged (still accurate), and every orphan (still on disk, still
  // tracked, so a future run keeps reporting it instead of losing track of it).
  const unchangedEntries = plan.writable.filter((e) => e.status === "unchanged");
  const stillTrackedOrphans = plan.orphaned;

  const filesForManifest = [
    ...written.map((e) => ({ path: e.path, content: e.content, generatedBy: e.generatedBy })),
    ...unchangedEntries.map((e) => ({ path: e.path, content: e.content, generatedBy: e.generatedBy })),
  ];

  const manifest = buildManifest(plan.includedProfiles, filesForManifest);
  // Carry orphaned entries forward with their last known hash (we didn't touch them).
  for (const orphan of stillTrackedOrphans) {
    const absolutePath = path.join(projectRoot, orphan.path);
    if (await fileExists(absolutePath)) {
      const content = await readFile(absolutePath, "utf8");
      manifest.files.push({ path: orphan.path, sha256: sha256Hex(content), generatedBy: orphan.generatedBy });
    }
  }

  const manifestPath = path.join(projectRoot, ".claude-foundry", "manifest.json");
  await mkdir(path.dirname(manifestPath), { recursive: true });
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n", "utf8");

  return { written, skipped, manifest };
}
